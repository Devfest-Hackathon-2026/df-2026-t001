/** 対象月（"YYYY-MM"）の祝日を「日（1..31）」の昇順で返す */
export function holidaysInMonth(monthStr: string): number[] {
  const prefix = `${monthStr}-`;
  const days: number[] = [];
  for (const key of Object.keys(HOLIDAYS)) {
    if (key.startsWith(prefix)) {
      const d = Number(key.slice(8, 10));
      if (d >= 1 && d <= 31) days.push(d);
    }
  }
  return days.sort((a, b) => a - b);
}
